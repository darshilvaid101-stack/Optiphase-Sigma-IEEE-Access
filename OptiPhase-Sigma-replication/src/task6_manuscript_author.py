"""Task 6 generator: writes every number, table, and provenance record of the manuscripts from stored outputs.

Outputs under manuscript/generated/: macros.tex (one \\newcommand per quantity), the booktabs tables, and
provenance.json (SHA-256 of every input). The curated bibliography is maintained in manuscript/ and is hashed here, not
copied. The prose never types a quantity by hand, so the text cannot drift from the data.
"""

import csv
import hashlib
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

from lib.crash_replacements import CRASH_REPLACEMENTS_PATH
from lib.kernel_catalog import all_kernels
from lib.kernel_registry import REPO_ROOT
from lib.manuscript_bibliography import CURATED_BIBLIOGRAPHY, bibliography_entries
from lib.manuscript_campaign import campaign_macros
from lib.manuscript_instcount import instcount_outputs, with_pass_time_waste
from lib.manuscript_lowering import lowering_macros
from lib.manuscript_macros import (
    agreement_macros,
    benchmark_macros,
    constant_macros,
    matrix_macros,
    noise_macros,
    pareto_macros,
    protocol_macros,
    r5_macros,
    rpb_macros,
    status_macros,
    sweep_macros,
    variant_macros,
)
from lib.manuscript_refinement import certificate_macros, refinement_macros
from lib.manuscript_tables import (
    encoding_table,
    pareto_table,
    r5_sequence_table,
    regime_table,
    rpb_table,
    smt_table,
)
from lib.manuscript_uncertainty import uncertainty_outputs
from lib.manuscript_witnesses import witness_macros
from lib.pipeline_plans import R3_PASSES, static_plans
from lib.r5_interference import interference_records, summarize
from lib.regime6_inputs import build_observations
from task5_z3_verifier_and_math import Z3_TIMEOUT_MS

MANUSCRIPT = REPO_ROOT / "manuscript"
GENERATED = MANUSCRIPT / "generated"
TELEMETRY = REPO_ROOT / "data" / "telemetry"
BENCHMARK_MANIFEST = REPO_ROOT / "data" / "benchmarks" / "bitcode_O0_canon" / "MANIFEST.json"
CONFIG = REPO_ROOT / "config"
PASS_VALIDITY = CONFIG / "llvm_newpm_pass_validity.json"
SUBSTITUTES = CONFIG / "llvm_newpm_substitutes.json"
PROVENANCE_PATH = GENERATED / "provenance.json"
MASTER_TABLE = TELEMETRY / "master_sweeps_28800.csv"
PROOF_TABLE = TELEMETRY / "z3_verification_proofs.csv"
PARETO_TABLE = TELEMETRY / "pareto_3d_frontiers.csv"
MPASS_TABLE = TELEMETRY / "m_pass_transition_matrix.csv"
LIE_TABLE = TELEMETRY / "lie_bracket_mean.csv"
RPB_SUMMARY = TELEMETRY / "rpb_summary.json"
BASELINES_PATH = TELEMETRY / "canonical_baselines.json"
REFINEMENT_REPORT = TELEMETRY / "refinement_analysis.json"
WITNESS_REPORT = TELEMETRY / "sat_witness_attribution.json"
AUDIT_PATH = TELEMETRY / "sweep_audit.jsonl"
CERTIFICATE_MANIFEST = REPO_ROOT / "data" / "smt2_certificates" / "manifest.json"
ENCODING_REPORT = TELEMETRY / "z3_encoding_agreement.json"
VARIANT_REPORT = TELEMETRY / "sweep_variant_checks.json"
PASS_CHECKS_PATH = TELEMETRY / "pass_checks.json"
LOWERING_PILOT_PATH = TELEMETRY / "lowering_pilot.json"
MACROS_HEADER = "% Generated by src/task6_manuscript_author.py. Do not edit by hand."


def read_csv(path):
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def file_sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_text(name, content):
    (GENERATED / name).write_text(content, encoding="utf-8")


def all_macros(inputs, uncertainty_macros):
    kernels = inputs["manifest"]["kernels"]
    master_rows = inputs["master"]
    lines = [MACROS_HEADER]
    lines += constant_macros()
    lines += benchmark_macros(kernels, inputs["manifest"])
    lines += protocol_macros(Z3_TIMEOUT_MS, inputs["validity"]["passes"], inputs["substitutes"])
    lines += sweep_macros(master_rows, len(kernels))
    lines += status_macros("Smt", inputs["proofs"], "z3_refinement_status")
    lines += noise_macros(master_rows, inputs["proofs"])
    lines += pareto_macros(inputs["pareto"], inputs["proofs"])
    lines += rpb_macros(inputs["rpb"])
    lines += matrix_macros("Mpass", inputs["mpass"], R3_PASSES)
    lines += matrix_macros("Lie", inputs["lie"], R3_PASSES)
    lines += r5_macros(summarize(interference_records(master_rows)))
    lines += variant_macros(inputs["variants"], master_rows)
    lines += agreement_macros(inputs["agreement"])
    lines += uncertainty_macros
    lines += refinement_macros(inputs["refinement"])
    lines += witness_macros(inputs["witnesses"])
    lines += campaign_macros(inputs["audit_text"])
    lines += certificate_macros(inputs["certificates"])
    lines += lowering_macros(inputs["lowering_pilot"])
    return "\n".join(lines) + "\n"


def all_tables(inputs, uncertainty_tables):
    suite_by_kernel = {row["kernel_id"]: row["suite_name"] for row in inputs["master"]}
    return {
        "table_regimes.tex": regime_table(inputs["master"]),
        "table_smt.tex": smt_table(inputs["proofs"]),
        "table_pareto.tex": pareto_table(inputs["pareto"], suite_by_kernel),
        "table_encoding.tex": encoding_table(inputs["agreement"]),
        "table_rpb.tex": rpb_table(inputs["rpb"]),
        "table_r5_sequences.tex": r5_sequence_table(inputs["master"]),
        **uncertainty_tables,
    }


def interference_observations(inputs):
    kernel_ids = [kernel.kernel_id for kernel in all_kernels()]
    observations, excluded = build_observations(kernel_ids, inputs["baselines"], static_plans(), inputs["master"])
    if excluded:
        raise ValueError(f"kernels without complete R2/R3 coverage: {excluded}")
    return observations


def load_inputs():
    return {
        "manifest": read_json(BENCHMARK_MANIFEST),
        "validity": read_json(PASS_VALIDITY),
        "substitutes": read_json(SUBSTITUTES),
        "master": read_csv(MASTER_TABLE),
        "proofs": read_csv(PROOF_TABLE),
        "pareto": read_csv(PARETO_TABLE),
        "mpass": read_csv(MPASS_TABLE),
        "lie": read_csv(LIE_TABLE),
        "rpb": read_json(RPB_SUMMARY),
        "baselines": read_json(BASELINES_PATH),
        "refinement": read_json(REFINEMENT_REPORT),
        "witnesses": read_json(WITNESS_REPORT),
        "audit_text": AUDIT_PATH.read_text(encoding="utf-8"),
        "certificates": read_json(CERTIFICATE_MANIFEST),
        "agreement": read_json(ENCODING_REPORT),
        "variants": read_json(VARIANT_REPORT),
        "pass_checks": read_json(PASS_CHECKS_PATH),
        "lowering_pilot": read_json(LOWERING_PILOT_PATH),
    }


def provenance_inputs():
    return [
        BENCHMARK_MANIFEST, PASS_VALIDITY, SUBSTITUTES, MASTER_TABLE, PROOF_TABLE, PARETO_TABLE, MPASS_TABLE,
        LIE_TABLE, RPB_SUMMARY, ENCODING_REPORT, VARIANT_REPORT, REFINEMENT_REPORT, WITNESS_REPORT,
        CERTIFICATE_MANIFEST, CURATED_BIBLIOGRAPHY, BASELINES_PATH, AUDIT_PATH, CRASH_REPLACEMENTS_PATH,
        PASS_CHECKS_PATH, LOWERING_PILOT_PATH,
    ]


def main():
    GENERATED.mkdir(parents=True, exist_ok=True)
    inputs = load_inputs()
    inputs["rpb"] = with_pass_time_waste(inputs["rpb"], inputs["master"])
    uncertainty_macros, uncertainty_tables = uncertainty_outputs(
        inputs["master"], inputs["proofs"], interference_observations(inputs), inputs["baselines"],
    )
    instcount_macros, instcount_tables = instcount_outputs(inputs["master"], inputs["pass_checks"])
    uncertainty_macros += instcount_macros
    uncertainty_tables.update(instcount_tables)
    write_text("macros.tex", all_macros(inputs, uncertainty_macros))
    for name, content in all_tables(inputs, uncertainty_tables).items():
        write_text(name, content)
    entry_count = len(bibliography_entries())
    provenance = {
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "bibliography_entries": entry_count,
        "inputs": {str(path.relative_to(REPO_ROOT)): file_sha256(path) for path in provenance_inputs()},
    }
    PROVENANCE_PATH.write_text(json.dumps(provenance, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"sweeps {len(inputs['master'])}, proofs {len(inputs['proofs'])}, bibliography entries {entry_count}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
